      choose: function (param) {
        for (var i = 0; i < this.list.length; i++) {
          if (param[this.idName] == this.list[i][this.idName]) {
            this.list[i].checked = !this.list[i].checked;
          }
        }
        this.chooseResult = [];
        this.chooseTitle = '';
        if (param[this.idName]) {
          for (var i = 0; i < this.list.length; i++) {
            if (this.list[i].checked && i > 0) {
              this.chooseResult.push(this.list[i]);
              this.chooseTitle += this.list[i][this.dataName] + ',';
              this.list[0].checked = false;
            }
          }
          this.chooseTitle = this.chooseTitle.replace(/\,$/, '');
        } else {
          for (var i = 0; i < this.list.length; i++) {
            if (i > 0) {
              this.list[i].checked = false;
            }
          }
          this.chooseTitle = this.dataTitle;
        }
        this.$emit('change-data', this.chooseResult);
      }
