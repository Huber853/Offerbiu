var dateHelper = {
  getDateModel: function (dateStr) {
    if (dateStr) {
      var arr = dateStr.split("-");
      return {
        year: arr.length > 0 ? arr[0] : "",
        month: arr.length > 1 ? arr[1] : "",
        day: arr.length > 2 ? arr[2] : "01"
      };
    }
  },
  getDateStr: function (dateModel) {
    if (dateModel) {
      return dateModel.year + "-" + dateModel.month + "-" + (dateModel.day || "01");
    }
  },
  timestampToDateStr: function (timestamp) {
    if (!timestamp) {
      return "";
    }
    try {
      if (typeof (timestamp) == "string") {
        timestamp = parseInt(timestamp);
      }
      var time = new Date(timestamp);
      var y = time.getFullYear();
      var m = time.getMonth() + 1;
      var d = time.getDate();
      var h = time.getHours();
      var mm = time.getMinutes();
      var s = time.getSeconds();
      return y + '-' + (m < 10 ? '0' + m : m) + '-' + (d < 10 ? '0' + d : d) + ' ' + (h < 10 ? '0' + h : h) + ':' + (mm < 10 ? '0' + mm : mm) + ':' + (s < 10 ? '0' + s : s);
    } catch (e) {
      return "";
    }
  },
  strToDate: function (dateObj) {
    if (typeof (dateObj) == "object") {
      return dateObj;
    }
    dateObj = dateObj.replace(/T/g, ' ').replace(/\.[\d]{3}Z/, '').replace(/(-)/g, '/');
    if (dateObj.indexOf(".") > 0) dateObj = dateObj.slice(0, dateObj.indexOf("."));

    return new Date(dateObj);
  }
};

